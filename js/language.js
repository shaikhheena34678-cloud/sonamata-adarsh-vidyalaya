/*=========================================================
        CHANGE LANGUAGE
=========================================================*/

function changeLanguage(language) {

    /*
        Check whether the selected language exists.
        If not, use English.
    */
    if (!translations[language]) {
        language = "en";
    }

    const currentTranslation = translations[language];


    /*=====================================================
            TRANSLATE NORMAL TEXT
    =====================================================*/

    const elements = document.querySelectorAll("[data-i18n]");

    elements.forEach(element => {

        /*
            Do not translate elements inside
            data-no-translate.
        */
        if (element.closest("[data-no-translate]")) {
            return;
        }

        const key = element.getAttribute("data-i18n");

        /*
            Only translate if the key exists.
        */
        if (
            Object.prototype.hasOwnProperty.call(
                currentTranslation,
                key
            )
        ) {

            /*
                Use innerHTML only when explicitly requested.

                Example:

                <h2
                    data-i18n="educating_minds"
                    data-i18n-html
                ></h2>
            */
            if (element.hasAttribute("data-i18n-html")) {

                element.innerHTML =
                    currentTranslation[key];

            } else {

                element.textContent =
                    currentTranslation[key];

            }
        }

    });


    /*=====================================================
            TRANSLATE PLACEHOLDERS
    =====================================================*/

    const placeholders =
        document.querySelectorAll(
            "[data-i18n-placeholder]"
        );

    placeholders.forEach(element => {

        if (element.closest("[data-no-translate]")) {
            return;
        }

        const key =
            element.getAttribute(
                "data-i18n-placeholder"
            );

        if (
            Object.prototype.hasOwnProperty.call(
                currentTranslation,
                key
            )
        ) {

            element.setAttribute(
                "placeholder",
                currentTranslation[key]
            );

        }

    });


    /*=====================================================
            TRANSLATE INPUT / BUTTON VALUES
    =====================================================*/

    const values =
        document.querySelectorAll(
            "[data-i18n-value]"
        );

    values.forEach(element => {

        if (element.closest("[data-no-translate]")) {
            return;
        }

        const key =
            element.getAttribute(
                "data-i18n-value"
            );

        if (
            Object.prototype.hasOwnProperty.call(
                currentTranslation,
                key
            )
        ) {

            element.value =
                currentTranslation[key];

        }

    });


    /*=====================================================
            TRANSLATE TITLE ATTRIBUTES
    =====================================================*/

    const titleElements =
        document.querySelectorAll(
            "[data-i18n-title]"
        );

    titleElements.forEach(element => {

        if (element.closest("[data-no-translate]")) {
            return;
        }

        const key =
            element.getAttribute(
                "data-i18n-title"
            );

        if (
            Object.prototype.hasOwnProperty.call(
                currentTranslation,
                key
            )
        ) {

            element.setAttribute(
                "title",
                currentTranslation[key]
            );

        }

    });


    /*=====================================================
            TRANSLATE ARIA LABELS
    =====================================================*/

    const ariaElements =
        document.querySelectorAll(
            "[data-i18n-aria-label]"
        );

    ariaElements.forEach(element => {

        if (element.closest("[data-no-translate]")) {
            return;
        }

        const key =
            element.getAttribute(
                "data-i18n-aria-label"
            );

        if (
            Object.prototype.hasOwnProperty.call(
                currentTranslation,
                key
            )
        ) {

            element.setAttribute(
                "aria-label",
                currentTranslation[key]
            );

        }

    });


    /*=====================================================
            SAVE LANGUAGE
    =====================================================*/

    try {

        localStorage.setItem(
            "selectedLanguage",
            language
        );

    } catch (error) {

        console.warn(
            "Could not save selected language:",
            error
        );

    }


    /*=====================================================
            UPDATE LANGUAGE DROPDOWN
    =====================================================*/

    const languageSelect =
        document.getElementById(
            "languageSelect"
        );

    if (languageSelect) {

        languageSelect.value =
            language;

    }


    /*=====================================================
            UPDATE LANGUAGE BUTTONS
    =====================================================*/

    const languageButtons =
        document.querySelectorAll(
            ".language-btn"
        );

    languageButtons.forEach(button => {

        const buttonLanguage =
            button.getAttribute(
                "data-lang"
            );

        button.classList.toggle(
            "active",
            buttonLanguage === language
        );

        /*
            Accessibility support
        */
        button.setAttribute(
            "aria-pressed",
            buttonLanguage === language
                ? "true"
                : "false"
        );

    });


    /*=====================================================
            UPDATE HTML LANG ATTRIBUTE
    =====================================================*/

    document.documentElement.lang =
        language;


    /*=====================================================
            UPDATE TEXT DIRECTION
            Both English and Marathi are LTR.
    =====================================================*/

    document.documentElement.dir = "ltr";


    /*=====================================================
            INFORM OTHER SCRIPTS
    =====================================================*/

    window.dispatchEvent(
        new CustomEvent(
            "languageChanged",
            {
                detail: {
                    language: language
                }
            }
        )
    );

}


/*=========================================================
        GET SAVED LANGUAGE
=========================================================*/

function getSavedLanguage() {

    let savedLanguage = "en";

    try {

        savedLanguage =
            localStorage.getItem(
                "selectedLanguage"
            ) || "en";

    } catch (error) {

        console.warn(
            "Could not read saved language:",
            error
        );

    }

    /*
        Make sure saved language actually exists.
    */
    if (!translations[savedLanguage]) {
        savedLanguage = "en";
    }

    return savedLanguage;
}


/*=========================================================
        INITIALIZE LANGUAGE SELECT
=========================================================*/

function initializeLanguageSelect() {

    const languageSelect =
        document.getElementById(
            "languageSelect"
        );

    if (!languageSelect) {
        return;
    }

    /*
        Set current language in dropdown.
    */
    languageSelect.value =
        getSavedLanguage();


    /*
        Prevent multiple event listeners
        if initialization happens again.
    */
    if (
        languageSelect.dataset.languageInitialized === "true"
    ) {
        return;
    }

    languageSelect.addEventListener(
        "change",
        function () {

            changeLanguage(
                this.value
            );

        }
    );

    languageSelect.dataset.languageInitialized =
        "true";
}


/*=========================================================
        INITIALIZE LANGUAGE BUTTONS
=========================================================*/

function initializeLanguageButtons() {

    const languageButtons =
        document.querySelectorAll(
            ".language-btn"
        );

    languageButtons.forEach(button => {

        /*
            Prevent duplicate click events.
        */
        if (
            button.dataset.languageInitialized === "true"
        ) {
            return;
        }

        button.addEventListener(
            "click",
            function () {

                const selectedLanguage =
                    this.getAttribute(
                        "data-lang"
                    );

                changeLanguage(
                    selectedLanguage
                );

            }
        );

        button.dataset.languageInitialized =
            "true";

    });

}


/*=========================================================
        INITIALIZE LANGUAGE SYSTEM
=========================================================*/

function initializeLanguageSystem() {

    /*
        Get saved language.
    */
    const language =
        getSavedLanguage();


    /*
        Initialize dropdown.
    */
    initializeLanguageSelect();


    /*
        Initialize buttons.
    */
    initializeLanguageButtons();


    /*
        Apply saved language.
    */
    changeLanguage(
        language
    );

}


/*=========================================================
        DOM READY
=========================================================*/

if (
    document.readyState === "loading"
) {

    document.addEventListener(
        "DOMContentLoaded",
        initializeLanguageSystem
    );

} else {

    /*
        Useful when this script is loaded
        after the DOM has already loaded.
    */
    initializeLanguageSystem();

}